export const fixRomanText = (text) => {
  if (!text) return ''
  // Fix API typo: 'lyyaaka' should be 'Iyyaaka'
  let fixed = text.replace(/\blyyaaka\b/gi, 'Iyyaaka')
  // Fix known API transliteration typos in 3:66
  fixed = fixed.replace(/\bbaajajtum\b/gi, 'haajajtum')
  fixed = fixed.replace(/\btuhaaajjoonaa\b/gi, 'tuhaajjoona')
  // Fix additional verified transliteration typo patterns
  fixed = fixed.replace(/\bmaaootiya\b/gi, 'maaa ootiya')
  fixed = fixed.replace(/\bulaaaika\b/gi, "ulaaa'ika")
  fixed = fixed.replace(/\bmutrafooaa\b/gi, 'mutrafoohaa')
  fixed = fixed.replace(/\bwallaeee\b/gi, 'Wallazee')
  fixed = fixed.replace(/\bsoooud\b/gi, "soo'ud")
  fixed = fixed.replace(/\baraiaitum\b/gi, "ara'aitum")
  fixed = fixed.replace(/\babuaaa'akum\b/gi, "abnaaa'akum")
  fixed = fixed.replace(/\bwa'lamoooannakum\b/gi, "wa'lamoo annakum")
  fixed = fixed.replace(/\bfa'um miyat\b/gi, "fa'ummiyat")
  fixed = fixed.replace(/\bkafar tum\b/gi, 'kafartum')
  fixed = fixed.replace(/\bahwaaa;ahum\b/gi, "ahwaaa'ahum")
  fixed = fixed.replace(/\bturja;ul\b/gi, "turja'ul")
  fixed = fixed.replace(/\bma;akum\b/gi, "ma'akum")
  fixed = fixed.replace(/\bba;d\b/gi, "ba'd")
  fixed = fixed.replace(/rabbih;;\s*kadhaalika/gi, 'rabbih; kadhaalika')
  // Some API records contain accidental doubled semicolons; collapse to single.
  fixed = fixed.replace(/;{2,}/g, ';')
  fixed = fixed.replace(/\blilmu;mineena\b/gi, "lilmu'mineena")
  fixed = fixed.replace(/\byu;minoo\b/gi, "yu'minoo")
  fixed = fixed.replace(/\bfabu;dal\b/gi, "fabu'dal")
  // Known local correction requested for 3:76 (also applied when regenerating from API)
  fixed = fixed.replace(/\bfainnal\s+laaha\b/gi, "fa'innallaaha")
  // Confirmed Arabic-aligned typo cleanup (applies to local/API regeneration paths)
  fixed = fixed.replace(/\bhuwad\b/gi, 'huwa')
  fixed = fixed.replace(/\bhuwaj\b/gi, 'huwa')
  fixed = fixed.replace(/\bfaddalnaahum;alal\b/gi, "faddalnaahum 'alal")
  fixed = fixed.replace(/\btanzi;un\b/gi, "tanzi'un")
  fixed = fixed.replace(/\bshai;in\b/gi, "shai'in")
  fixed = fixed.replace(/\bya;mal\b/gi, "ya'mal")
  // Fix malformed sequence seen in 68:51: "iny-yakaadul" -> "in yakaadul"
  fixed = fixed.replace(/\biny-yakaadul\b/gi, 'in yakaadul')
  // Fix API quirk: triple+ consonants → double (e.g. "innnaa" → "innaa")
  fixed = fixed.replace(/([bcdfghjklmnpqrstvwxyz])\1{2,}/gi, '$1$1')
  // Fix API quirk: quadruple+ vowels → triple (e.g. "moosaaaa" → "moosaaa")
  fixed = fixed.replace(/([aeiou])\1{3,}/gi, '$1$1$1')
  return fixed.replace(/[a-zA-Z']+/g, word => {
    const lower = word.toLowerCase()
    // Check general word corrections first
    const corrected = WORD_CORRECTIONS[lower]
    if (corrected) {
      const corrLower = corrected.toLowerCase()
      // After correcting, check if the corrected word also needs DHAAL conversion
      const dhaalOfCorrected = DHAAL_WORDS[corrLower]
      if (dhaalOfCorrected) {
        if (word[0] === word[0].toUpperCase()) return dhaalOfCorrected[0].toUpperCase() + dhaalOfCorrected.slice(1)
        return dhaalOfCorrected
      }
      // Also check apostrophe-prefixed corrections (e.g. 'azeeem → 'azeem → 'adheem)
      if (corrLower.startsWith("'") && corrLower.length > 1) {
        const withoutApo = corrLower.slice(1)
        if (DHAAL_WORDS[withoutApo]) return "'" + DHAAL_WORDS[withoutApo]
      }
      if (word[0] === word[0].toUpperCase()) return corrected[0].toUpperCase() + corrected.slice(1)
      return corrected
    }
    // Exact lookup only. DHAAL_WORDS covers every token the API emits across all
    // 6236 verses, so matching by stripped prefix/suffix would only ever fire on
    // words absent from the map — corrupting genuine ز words like 'azamut or waznu.
    const fullMatch = DHAAL_WORDS[lower]
    if (fullMatch) {
      if (word[0] === word[0].toUpperCase()) return fullMatch[0].toUpperCase() + fullMatch.slice(1)
      return fullMatch
    }
    if (lower.startsWith("'") && lower.length > 1) {
      const apoMatch = DHAAL_WORDS[lower.slice(1)]
      if (apoMatch) {
        const first = word[1]
        const upper = first === first.toUpperCase() && first !== first.toLowerCase()
        return "'" + (upper ? apoMatch[0].toUpperCase() + apoMatch.slice(1) : apoMatch)
      }
    }
    return word
  })
}

const getLocalSupportDataUrl = (surahNumber) => `/quran-support/${surahNumber}.json`

const fetchLocalSupportData = async (surahNumber, signal) => {
  try {
    const res = await fetchWithTimeout(getLocalSupportDataUrl(surahNumber), signal, 2500, 0)
    if (!res.ok) return null
    const data = await res.json()
    return Array.isArray(data?.verses) ? data.verses : null
  } catch (_) {
    return null
  }
}

const fetchSupportData = async (surahNumber, signal) => {
  const localSupportData = await fetchLocalSupportData(surahNumber, signal)
  if (localSupportData) return localSupportData
  return fetchRemoteSupportData(surahNumber, signal)
}

const fetchRemoteSupportData = async (surahNumber, signal) => {
  const [englishRes, romanRes, teluguRes] = await Promise.all([
    fetchWithTimeout(`https://api.alquran.cloud/v1/surah/${surahNumber}/en.sahih`, signal),
    fetchWithTimeout(`https://api.alquran.cloud/v1/surah/${surahNumber}/en.transliteration`, signal),
    fetchWithTimeout(`https://api.quran.com/api/v4/quran/translations/227?chapter_number=${surahNumber}`, signal)
  ])

  const [englishData, romanData] = await Promise.all([
    englishRes.json(),
    romanRes.json()
  ])

  let teluguTranslations = []
  if (teluguRes.ok) {
    const teluguData = await teluguRes.json()
    if (teluguData?.translations) {
      teluguTranslations = teluguData.translations.map((item, i) => ({
        number: i + 1,
        telugu: stripHtml(item.text || '')
      }))
    }
  }

  const englishAyahs = englishData.code === 200 ? englishData.data?.ayahs || [] : []
  const romanAyahs = romanData.code === 200 ? romanData.data?.ayahs || [] : []
  const englishMap = Object.fromEntries(englishAyahs.map(v => [v.numberInSurah, v]))
  const romanMap = Object.fromEntries(romanAyahs.map(v => [v.numberInSurah, v]))
  const teluguMap = Object.fromEntries(teluguTranslations.map(v => [v.number, v]))
  const verseNumbers = new Set([
    ...Object.keys(englishMap).map(Number),
    ...Object.keys(romanMap).map(Number),
    ...Object.keys(teluguMap).map(Number)
  ])

  return Array.from(verseNumbers)
    .sort((a, b) => a - b)
    .map((number) => ({
      number,
      roman: fixRomanText(romanMap[number]?.text?.trim() || ''),
      telugu: teluguMap[number]?.telugu || '',
      translation: englishMap[number]?.text || '',
    }))
}

// Fetch with timeout, abort support, and retry
const fetchWithTimeout = async (url, signal, timeoutMs = 15000, retries = 1) => {
  for (let attempt = 0; attempt <= retries; attempt++) {
    const controller = signal ? null : new AbortController()
    const fetchSignal = signal || controller?.signal
    const timeout = setTimeout(() => controller?.abort(), timeoutMs)
    try {
      const res = await fetch(url, { signal: fetchSignal })
      clearTimeout(timeout)
      return res
    } catch (err) {
      clearTimeout(timeout)
      if (attempt === retries || err.name === 'AbortError') throw err
      // Brief delay before retry
      await new Promise(r => setTimeout(r, 500))
    }
  }
}

// Internal bismillah text fetch (for stripping from verse 1)
const getBismillahText = async () => {
  if (bismillahCache?._rawText) return bismillahCache._rawText
  try {
    const res = await fetchWithTimeout('https://api.quran.com/api/v4/quran/verses/uthmani?chapter_number=1')
    const data = await res.json()
    if (data?.verses?.[0]?.text_uthmani) {
      const text = data.verses[0].text_uthmani.trim()
      if (!bismillahCache) bismillahCache = {}
      bismillahCache._rawText = text
      return text
    }
  } catch (_) { /* continue without */ }
  return ''
}

// Fetch complete surah data from APIs
export const fetchSurahFromAPI = async (surahNumber, signal) => {
  try {
    const arabicDataPromise = fetchWithTimeout(
      `https://api.quran.com/api/v4/quran/verses/uthmani?chapter_number=${surahNumber}`,
      signal
    ).then(res => res.json())
    const supportDataPromise = fetchSupportData(surahNumber, signal)
    const bismillahPromise = surahNumber !== 1 && surahNumber !== 9
      ? getBismillahText()
      : Promise.resolve('')

    const [arabicData, supportVerses, bismillahText] = await Promise.all([
      arabicDataPromise,
      supportDataPromise,
      bismillahPromise,
    ])

    if (!arabicData?.verses?.length) return []
    const supportMap = Object.fromEntries((supportVerses || []).map(v => [v.number, v]))

    const verses = arabicData.verses.map((ayah, index) => {
      const numberInSurah = Number((ayah.verse_key || '').split(':')[1]) || (index + 1)
      const supportVerse = supportMap[numberInSurah]

      let arabicText = (ayah.text_uthmani || '').trim()

      if (surahNumber !== 1 && surahNumber !== 9 && numberInSurah === 1 && bismillahText) {
        const normalized = arabicText.replace(/\s+/g, ' ').trim()
        const normalizedBismillah = bismillahText.replace(/\s+/g, ' ').trim()
        if (normalized.startsWith(normalizedBismillah)) {
          arabicText = normalized.substring(normalizedBismillah.length).trim()
        }
      }

      return {
        number: numberInSurah,
        globalNumber: ayah.id,
        arabic: arabicText,
        roman: supportVerse?.roman || '',
        telugu: supportVerse?.telugu || '',
        translation: supportVerse?.translation || '',
      }
    })

    addToVerseCache(surahNumber, verses)
    return verses
  } catch (error) {
    if (error.name === 'AbortError') throw error
    console.error('Error fetching surah:', error)
    return []
  }
}

// Get verses with caching + dedup
export const getSurahVerses = async (surahNumber, signal) => {
  if (verseCache[surahNumber]) return verseCache[surahNumber]
  // Dedup: if a request is already in-flight, reuse it
  if (pendingRequests[surahNumber]) return pendingRequests[surahNumber]
  const promise = fetchSurahFromAPI(surahNumber, signal).finally(() => {
    delete pendingRequests[surahNumber]
  })
  pendingRequests[surahNumber] = promise
  return promise
}

// Fetch Bismillah data for display (cached)
export const fetchBismillah = async () => {
  if (bismillahCache?.arabic) return bismillahCache
  try {
    const [arabicRes, romanRes] = await Promise.all([
      fetchWithTimeout('https://api.quran.com/api/v4/quran/verses/uthmani?chapter_number=1'),
      fetchWithTimeout('https://api.alquran.cloud/v1/surah/1/en.transliteration')
    ])
    const [arabicData, romanData] = await Promise.all([arabicRes.json(), romanRes.json()])
    if (arabicData?.verses?.[0]?.text_uthmani && romanData.code === 200) {
      const result = {
        arabic: arabicData.verses[0].text_uthmani.trim(),
        roman: fixRomanText(romanData.data.ayahs[0].text.trim()),
        _rawText: arabicData.verses[0].text_uthmani.trim()
      }
      bismillahCache = result
      return result
    }
  } catch (_) { /* silent fail */ }
  return null
}
