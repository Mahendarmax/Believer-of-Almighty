const fixRomanText = (text) => {
  if (!text) return ''
  // Fix API typo: 'lyyaaka' should be 'Iyyaaka'
  let fixed = text.replace(/\blyyaaka\b/gi, 'Iyyaaka')
  // Fix API quirk: triple+ consonants → double (e.g. "innnaa" → "innaa")
  fixed = fixed.replace(/([bcdfghjklmnpqrstvwxyz])\1{2,}/gi, '$1$1')
  // Fix API quirk: quadruple+ vowels → triple (e.g. "moosaaaa" → "moosaaa")
  fixed = fixed.replace(/([aeiou])\1{3,}/gi, '$1$1$1')
  return fixed.replace(/[a-zA-Z']+/g, word => {
    const lower = word.toLowerCase()
    // Check general word corrections first
    const corrected = WORD_CORRECTIONS[lower]
    if (corrected) {
      const corrLower = corrected.toLowerCase()
      // After correcting, check if the corrected word also needs DHAAL conversion
      const dhaalOfCorrected = DHAAL_WORDS[corrLower]
      if (dhaalOfCorrected) {
        if (word[0] === word[0].toUpperCase()) return dhaalOfCorrected[0].toUpperCase() + dhaalOfCorrected.slice(1)
        return dhaalOfCorrected
      }
      // Also check apostrophe-prefixed corrections (e.g. 'azeeem → 'azeem → 'adheem)
      if (corrLower.startsWith("'") && corrLower.length > 1) {
        const withoutApo = corrLower.slice(1)
        if (DHAAL_WORDS[withoutApo]) return "'" + DHAAL_WORDS[withoutApo]
      }
      if (word[0] === word[0].toUpperCase()) return corrected[0].toUpperCase() + corrected.slice(1)
      return corrected
    }
    // Try full word first (e.g. 'allazeena')
    const fullMatch = DHAAL_WORDS[lower]
    // Handle leading apostrophe: strip it, check DHAAL_WORDS, reattach (e.g. 'azeem → 'adheem)
    if (!fullMatch && lower.startsWith("'") && lower.length > 1) {
      const withoutApo = lower.slice(1)
      const apoMatch = DHAAL_WORDS[withoutApo]
      if (apoMatch) {
        return "'" + apoMatch
      }
      // Try suffix-stripping with apostrophe (e.g. 'azaaba → 'adhaab + a)
      for (let s = 1; s <= 2; s++) {
        if (withoutApo.length > s + 2) {
          const core = withoutApo.slice(0, -s)
          const tail = withoutApo.slice(-s)
          if (DHAAL_WORDS[core]) {
            return "'" + DHAAL_WORDS[core] + tail
          }
        }
      }
    }
    if (fullMatch) {
      if (word[0] === word[0].toUpperCase()) return fullMatch[0].toUpperCase() + fullMatch.slice(1)
      return fullMatch
    }
    // Handle apostrophe-joined words (e.g. bi'azaabin → bi'adhaabin, Allazeena'aahatta → Alladheena'aahatta)
    const apoIdx = word.indexOf("'")
    if (apoIdx > 0 && apoIdx < word.length - 1) {
      const prefix = word.slice(0, apoIdx)
      const suffix = word.slice(apoIdx + 1)
      const prefixLower = prefix.toLowerCase()
      const suffixLower = suffix.toLowerCase()
      const prefixMatch = DHAAL_WORDS[prefixLower]
      const suffixMatch = DHAAL_WORDS[suffixLower]
      const fixedPrefix = prefixMatch
        ? (prefix[0] === prefix[0].toUpperCase() ? prefixMatch[0].toUpperCase() + prefixMatch.slice(1) : prefixMatch)
        : prefix
      const fixedSuffix = suffixMatch || suffix
      return fixedPrefix + "'" + fixedSuffix
    }
    // Prefix/suffix stripping for compound dhaal words (e.g. lillazeena → lilladheena)
    const DHAAL_PREFIXES = ['lil', 'bil', 'kal', 'fal', 'wal', 'bi', 'fa', 'wa', 'li', 'la', 'ka']
    for (const pfx of DHAAL_PREFIXES) {
      if (lower.startsWith(pfx) && lower.length > pfx.length + 2) {
        const remainder = lower.slice(pfx.length)
        if (DHAAL_WORDS[remainder]) {
          const result = pfx + DHAAL_WORDS[remainder]
          if (word[0] === word[0].toUpperCase()) return result[0].toUpperCase() + result.slice(1)
          return result
        }
        // Try stripping 1-2 suffix chars from remainder
        for (let s = 1; s <= 2; s++) {
          if (remainder.length > s + 2) {
            const core = remainder.slice(0, -s)
            const tail = remainder.slice(-s)
            if (DHAAL_WORDS[core]) {
              const result = pfx + DHAAL_WORDS[core] + tail
              if (word[0] === word[0].toUpperCase()) return result[0].toUpperCase() + result.slice(1)
              return result
            }
          }
        }
      }
    }
    // Suffix-only stripping (e.g. lazeenat → lazeena→ladheena + t)
    for (let s = 1; s <= 2; s++) {
      if (lower.length > s + 3) {
        const core = lower.slice(0, -s)
        const tail = lower.slice(-s)
        if (DHAAL_WORDS[core]) {
          const result = DHAAL_WORDS[core] + tail
          if (word[0] === word[0].toUpperCase()) return result[0].toUpperCase() + result.slice(1)
          return result
        }
      }
    }
    return word
  })
}

// Fetch with timeout, abort support, and retry
const fetchWithTimeout = async (url, signal, timeoutMs = 15000, retries = 1) => {
  for (let attempt = 0; attempt <= retries; attempt++) {
    const controller = signal ? null : new AbortController()
    const fetchSignal = signal || controller?.signal
    const timeout = setTimeout(() => controller?.abort(), timeoutMs)
    try {
      const res = await fetch(url, { signal: fetchSignal })
      clearTimeout(timeout)
      return res
    } catch (err) {
      clearTimeout(timeout)
      if (attempt === retries || err.name === 'AbortError') throw err
      // Brief delay before retry
      await new Promise(r => setTimeout(r, 500))
    }
  }
}

// Internal bismillah text fetch (for stripping from verse 1)
const getBismillahText = async () => {
  if (bismillahCache?._rawText) return bismillahCache._rawText
  try {
    const res = await fetchWithTimeout('https://api.alquran.cloud/v1/surah/1')
    const data = await res.json()
    if (data.code === 200 && data.data?.ayahs?.[0]) {
      const text = data.data.ayahs[0].text.trim()
      if (!bismillahCache) bismillahCache = {}
      bismillahCache._rawText = text
      return text
    }
  } catch (_) { /* continue without */ }
  return ''
}

// Fetch complete surah data from APIs
export const fetchSurahFromAPI = async (surahNumber, signal) => {
  try {
    const [arabicRes, englishRes, romanRes, teluguRes] = await Promise.all([
      fetchWithTimeout(`https://api.alquran.cloud/v1/surah/${surahNumber}`, signal),
      fetchWithTimeout(`https://api.alquran.cloud/v1/surah/${surahNumber}/en.sahih`, signal),
      fetchWithTimeout(`https://api.alquran.cloud/v1/surah/${surahNumber}/en.transliteration`, signal),
      fetchWithTimeout(`https://api.quran.com/api/v4/quran/translations/227?chapter_number=${surahNumber}`, signal)
    ])

    const [arabicData, englishData, romanData] = await Promise.all([
      arabicRes.json(),
      englishRes.json(),
      romanRes.json()
    ])

    let teluguTranslations = []
    if (teluguRes.ok) {
      const teluguData = await teluguRes.json()
      if (teluguData?.translations) {
        teluguTranslations = teluguData.translations.map((item, i) => ({
          numberInSurah: i + 1,
          text: stripHtml(item.text || '')
        }))
      }
    }

    if (arabicData.code !== 200 || !arabicData.data) return []

    const englishAyahs = englishData.code === 200 ? englishData.data?.ayahs || [] : []
    const romanAyahs = romanData.code === 200 ? romanData.data?.ayahs || [] : []

    // Build O(1) lookup maps instead of O(n) find() per verse
    const englishMap = Object.fromEntries(englishAyahs.map(v => [v.numberInSurah, v]))
    const romanMap = Object.fromEntries(romanAyahs.map(v => [v.numberInSurah, v]))
    const teluguMap = Object.fromEntries(teluguTranslations.map(v => [v.numberInSurah, v]))

    // Get Bismillah text for removal from verse 1
    let bismillahText = ''
    if (surahNumber !== 1 && surahNumber !== 9) {
      bismillahText = await getBismillahText()
    }

    const verses = arabicData.data.ayahs.map((ayah) => {
      const engVerse = englishMap[ayah.numberInSurah]
      const romVerse = romanMap[ayah.numberInSurah]
      const telVerse = teluguMap[ayah.numberInSurah]

      let arabicText = ayah.text.trim()

      if (surahNumber !== 1 && surahNumber !== 9 && ayah.numberInSurah === 1 && bismillahText) {
        const normalized = arabicText.replace(/\s+/g, ' ').trim()
        const normalizedBismillah = bismillahText.replace(/\s+/g, ' ').trim()
        if (normalized.startsWith(normalizedBismillah)) {
          arabicText = normalized.substring(normalizedBismillah.length).trim()
        }
      }

      return {
        number: ayah.numberInSurah,
        globalNumber: ayah.number,
        arabic: arabicText,
        roman: fixRomanText(romVerse?.text?.trim() || ''),
        telugu: telVerse?.text || '',
        translation: engVerse?.text || '',
      }
    })

    addToVerseCache(surahNumber, verses)
    return verses
  } catch (error) {
    if (error.name === 'AbortError') throw error
    console.error('Error fetching surah:', error)
    return []
  }
}

// Get verses with caching + dedup
export const getSurahVerses = async (surahNumber, signal) => {
  if (verseCache[surahNumber]) return verseCache[surahNumber]
  // Dedup: if a request is already in-flight, reuse it
  if (pendingRequests[surahNumber]) return pendingRequests[surahNumber]
  const promise = fetchSurahFromAPI(surahNumber, signal).finally(() => {
    delete pendingRequests[surahNumber]
  })
  pendingRequests[surahNumber] = promise
  return promise
}

// Fetch Bismillah data for display (cached)
export const fetchBismillah = async () => {
  if (bismillahCache?.arabic) return bismillahCache
  try {
    const [arabicRes, romanRes] = await Promise.all([
      fetchWithTimeout('https://api.alquran.cloud/v1/surah/1'),
      fetchWithTimeout('https://api.alquran.cloud/v1/surah/1/en.transliteration')
    ])
    const [arabicData, romanData] = await Promise.all([arabicRes.json(), romanRes.json()])
    if (arabicData.code === 200 && romanData.code === 200) {
      const result = {
        arabic: arabicData.data.ayahs[0].text.trim(),
        roman: fixRomanText(romanData.data.ayahs[0].text.trim()),
        _rawText: arabicData.data.ayahs[0].text.trim()
      }
      bismillahCache = result
      return result
    }
  } catch (_) { /* silent fail */ }
  return null
}
